// نسخه‌ی جاری = اولین نسخه‌ی فهرست
function changelog_current() { return CHANGELOG[0]['version']; }

// شناسه => ردیف (با نسخه و تاریخ)
function changelog_index() {
    static $idx = null;
    if ($idx !== null) return $idx;
    $idx = [];
    foreach (CHANGELOG as $v) foreach ($v['items'] as $it) $idx[$it['id']] = $it + ['version' => $v['version'], 'date' => $v['date']];
    return $idx;
}
